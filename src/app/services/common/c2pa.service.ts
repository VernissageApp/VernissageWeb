import { isPlatformBrowser } from '@angular/common';
import { inject, Injectable, PLATFORM_ID } from '@angular/core';
import type { C2paSdk, Reader } from '@contentauth/c2pa-web';
import { C2paContentCredentials } from 'src/app/models/c2pa-content-credentials';
import { C2paManifest } from 'src/app/models/c2pa-manifest';
import { C2paManifestStore } from 'src/app/models/c2pa-manifest-store';
import { C2paValidationStatus } from 'src/app/models/c2pa-validation-status';
import { C2paValidationResults } from 'src/app/models/c2pa-validation-results';
import { ImageMimeTypeService } from './image-mime-type.service';

/**
 * Reads and normalizes C2PA Content Credentials metadata from image assets in the browser.
 * The service is used by status details to detect verifiable provenance data and expose
 * a compact view model for the Level 1 panel and Level 2 disclosure dialog.
 *
 * Relevant developer resources:
 * - Tutorial: https://learn.contentauthenticity.org
 * - Libraries: https://opensource.contentauthenticity.org/docs/getting-started/
 * - Specification: https://spec.c2pa.org/specifications/specifications/2.4/specs/C2PA_Specification.html
 *
 * Verification tools:
 * - JSON viewer: https://c2paviewer.com
 * - Adobe Inspect: https://contentauthenticity.adobe.com/inspect
 * - Content Authenticity Verify: https://verify.contentauthenticity.org
 * - Sony Digital Signature Self Checker: https://digitalsignatureself-checker.authenticity.sony.net/page/digitalSignatureSelfChecker
 */
@Injectable({
    providedIn: 'root'
})
export class C2paService {
    private readonly aiGeneratedDigitalSourceTypeMarkers = [
        'trainedalgorithmicmedia',
        'compositewithtrainedalgorithmicmedia',
        'compositesynthetic',
        'virtualrecording'
    ];

    private readonly aiGeneratedTextMarkers = [
        'generative ai',
        'ai generated',
        'generated by ai',
        'created by ai',
        'created using generative ai',
        'trained algorithmic',
        'synthid',
        'gpt-image',
        'dall-e',
        'dalle',
        'imagen',
        'midjourney',
        'stable diffusion',
        'stability ai',
        'adobe firefly',
        'firefly',
        'bing image creator',
        'microsoft designer',
        'meta ai',
        'ideogram',
        'leonardo.ai',
        'runway',
        'black forest labs'
    ];

    private platformId = inject(PLATFORM_ID);
    private imageMimeTypeService = inject(ImageMimeTypeService);
    private readonly initializationTimeoutMs = 15000;
    private c2paPromise?: Promise<C2paSdk>;
    private manifestInfoByUrl = new Map<string, Promise<C2paContentCredentials | undefined>>();

    public async hasContentCredentials(file: Blob, mimeType = file.type): Promise<boolean> {
        if (!isPlatformBrowser(this.platformId)) {
            return false;
        }

        let reader: Reader | null = null;
        try {
            const c2pa = await this.getC2paInstance();
            // Upload consent depends on presence, not signature validity or trust.
            reader = await c2pa.reader.fromBlob(await this.imageMimeTypeService.resolveImageMimeType(file, mimeType), file, {
                verify: { verifyAfterReading: false, verifyTrust: false }
            });
            return reader !== null;
        } catch {
            // Never preserve all metadata without an explicit confirmation.
            return false;
        } finally {
            await reader?.free();
        }
    }

    public async getContentCredentials(imageUrl?: string): Promise<C2paContentCredentials | undefined> {
        if (!imageUrl || !isPlatformBrowser(this.platformId)) {
            return undefined;
        }

        const cachedManifestInfo = this.manifestInfoByUrl.get(imageUrl);
        if (cachedManifestInfo) {
            return cachedManifestInfo;
        }

        const manifestInfo = this.readContentCredentials(imageUrl).then(contentCredentials => {
            if (!contentCredentials) {
                this.manifestInfoByUrl.delete(imageUrl);
            }

            return contentCredentials;
        });
        this.manifestInfoByUrl.set(imageUrl, manifestInfo);

        return manifestInfo;
    }

    private async getC2paInstance(): Promise<C2paSdk> {
        if (!this.c2paPromise) {
            this.c2paPromise = this.initializeC2pa().catch(error => {
                this.c2paPromise = undefined;
                throw error;
            });
        }

        return this.c2paPromise;
    }

    private async initializeC2pa(): Promise<C2paSdk> {
        let timedOut = false;
        let timeout: ReturnType<typeof setTimeout> | undefined;
        const initialization = (async () => {
            const sdk = await this.loadC2paSdk();
            if (timedOut) {
                sdk.dispose();
            }
            return sdk;
        })();

        try {
            return await Promise.race([
                initialization,
                new Promise<never>((_, reject) => {
                    timeout = setTimeout(() => {
                        timedOut = true;
                        reject(new Error('C2PA initialization timed out.'));
                    }, this.initializationTimeoutMs);
                })
            ]);
        } finally {
            clearTimeout(timeout);
        }
    }

    private async loadC2paSdk(): Promise<C2paSdk> {
        const { createC2pa } = await import('@contentauth/c2pa-web/inline');
        return createC2pa();
    }

    private async readContentCredentials(imageUrl: string): Promise<C2paContentCredentials | undefined> {
        let reader: Reader | null = null;

        try {
            const response = await fetch(imageUrl, {
                cache: 'no-store',
                mode: 'cors'
            });
            if (!response.ok) {
                return undefined;
            }

            const blob = await response.blob();
            const c2pa = await this.getC2paInstance();
            reader = await c2pa.reader.fromBlob(await this.imageMimeTypeService.resolveImageMimeType(blob), blob);
            if (!reader) {
                return undefined;
            }

            const manifestStore = await reader.manifestStore() as C2paManifestStore | undefined;
            const activeManifest = this.getActiveManifest(manifestStore);
            const validationStatuses = [
                ...(manifestStore?.validation_status ?? []),
                ...(activeManifest?.validation_status ?? [])
            ];

            if (!activeManifest) {
                return undefined;
            }

            const validationState = manifestStore?.validation_state;
            const failures = [
                ...validationStatuses.filter(status => status.success === false),
                ...this.getValidationFailures(manifestStore?.validation_results),
                ...this.getValidationFailures(activeManifest.validation_results)
            ].filter(status => status.code !== 'signingCredential.untrusted');
            const validationErrors = failures.filter((status, index) =>
                failures.findIndex(other => other.code === status.code && other.explanation === status.explanation) === index);
            const verificationStatus = validationState === 'Invalid' || validationErrors.length > 0
                ? 'invalid'
                : validationState === 'Trusted'
                    ? 'verified'
                    : validationState === 'Valid' ? 'untrusted' : 'unknown';

            return {
                author: this.getAuthor(activeManifest),
                appOrDeviceUsed: this.getAppOrDeviceUsed(activeManifest, manifestStore),
                aiGenerated: this.isAiGenerated(activeManifest, manifestStore),
                identity: this.getIdentity(activeManifest),
                actions: this.getActionsLabel(activeManifest),
                title: activeManifest.title,
                format: activeManifest.format,
                claimGenerator: this.getClaimGeneratorName(activeManifest),
                softwareAgent: this.getSoftwareAgent(activeManifest),
                signatureIssuer: activeManifest.signature_info?.issuer,
                signatureTime: activeManifest.signature_info?.time,
                ingredientsCount: activeManifest.ingredients?.length ?? 0,
                actionsCount: this.getActionsCount(activeManifest),
                validationStatuses,
                verificationStatus,
                validationErrors,
                validationState: manifestStore?.validation_state ?? undefined,
                verifyUrl: this.getVerifyUrl(imageUrl),
                manifest: activeManifest
            };
        } catch {
            return undefined;
        } finally {
            await reader?.free();
        }
    }

    private getActiveManifest(manifestStore?: C2paManifestStore): C2paManifest | undefined {
        const activeManifestLabel = manifestStore?.active_manifest;
        const manifests = manifestStore?.manifests;

        if (!activeManifestLabel || !manifests) {
            return undefined;
        }

        return manifests[activeManifestLabel];
    }

    private getActionsCount(manifest: C2paManifest): number {
        return manifest.assertions
            ?.flatMap(assertion => this.getActions(assertion.data))
            .length ?? 0;
    }

    private getAuthor(manifest: C2paManifest): string | undefined {
        const creativeWorkAssertion = manifest.assertions?.find(assertion => assertion.label?.includes('schema-org.CreativeWork'));
        const author = this.getStringValue(creativeWorkAssertion?.data, 'author');
        if (author) {
            return author;
        }

        return this.getStringValue(creativeWorkAssertion?.data, 'creator');
    }

    private getSoftwareAgent(manifest: C2paManifest): string | undefined {
        const actionWithSoftwareAgent = manifest.assertions
            ?.flatMap(assertion => this.getActions(assertion.data))
            .find(action => this.hasObjectProperty(action, 'softwareAgent'));

        const softwareAgent = this.getObjectProperty(actionWithSoftwareAgent, 'softwareAgent');
        return this.getSoftwareAgentName(softwareAgent);
    }

    private getIdentity(manifest: C2paManifest): string | undefined {
        const identityAssertion = manifest.assertions?.find(assertion => assertion.label === 'cawg.identity');
        const signatureInfo = this.getObjectProperty(identityAssertion?.data, 'signature_info');

        return this.getStringValue(signatureInfo, 'issuer') ?? this.getAuthor(manifest);
    }

    private getActionsLabel(manifest: C2paManifest): string | undefined {
        const actions = manifest.assertions
            ?.flatMap(assertion => this.getActions(assertion.data))
            .map(action => this.getStringValue(action, 'action'))
            .filter((action): action is string => !!action && action.length > 0)
            .map(action => action.replace(/^c2pa\./, '').replaceAll('_', ' '));

        if (!actions || actions.length === 0) {
            return undefined;
        }

        return Array.from(new Set(actions)).join(', ');
    }

    private getAppOrDeviceUsed(manifest: C2paManifest, manifestStore?: C2paManifestStore): string | undefined {
        const parentIngredientManifest = this.getParentIngredientManifest(manifest, manifestStore);
        return this.getClaimGeneratorName(parentIngredientManifest) ?? this.getClaimGeneratorName(manifest);
    }

    private getParentIngredientManifest(manifest: C2paManifest, manifestStore?: C2paManifestStore): C2paManifest | undefined {
        const parentIngredientManifestLabel = manifest.ingredients
            ?.map(ingredient => ingredient.active_manifest)
            .find(label => label && label.length > 0);

        if (!parentIngredientManifestLabel) {
            return undefined;
        }

        return manifestStore?.manifests?.[parentIngredientManifestLabel];
    }

    private isAiGenerated(manifest: C2paManifest, manifestStore?: C2paManifestStore): boolean {
        const manifests = this.getRelatedManifests(manifest, manifestStore);

        return manifests.some(relatedManifest => {
            return this.hasAiGeneratedDigitalSourceType(relatedManifest)
                || this.hasAiGeneratedTextMarker(relatedManifest);
        });
    }

    private getRelatedManifests(manifest: C2paManifest, manifestStore?: C2paManifestStore): C2paManifest[] {
        const relatedManifests: C2paManifest[] = [];
        const visitedManifests = new Set<C2paManifest>();

        const appendManifest = (internalManifest?: C2paManifest): void => {
            if (!internalManifest || visitedManifests.has(internalManifest)) {
                return;
            }

            visitedManifests.add(internalManifest);
            relatedManifests.push(internalManifest);

            internalManifest.ingredients
                ?.map(ingredient => ingredient.active_manifest)
                .filter((label): label is string => !!label && label.length > 0)
                .forEach(label => appendManifest(manifestStore?.manifests?.[label]));
        };

        appendManifest(manifest);

        return relatedManifests;
    }

    private hasAiGeneratedDigitalSourceType(manifest: C2paManifest): boolean {
        return manifest.assertions
            ?.flatMap(assertion => this.getActions(assertion.data))
            .some(action => {
                const digitalSourceType = this.getStringValue(action, 'digitalSourceType')?.toLowerCase();
                if (!digitalSourceType) {
                    return false;
                }

                return this.aiGeneratedDigitalSourceTypeMarkers.some(marker => digitalSourceType.includes(marker));
            }) ?? false;
    }

    private hasAiGeneratedTextMarker(manifest: C2paManifest): boolean {
        const metadataValues = [
            this.getClaimGeneratorName(manifest),
            this.getSoftwareAgent(manifest),
            manifest.signature_info?.issuer,
            manifest.signature_info?.common_name,
            ...this.getActionTextValues(manifest)
        ];

        return metadataValues
            .filter((value): value is string => !!value && value.length > 0)
            .some(value => {
                const normalizedValue = value.toLowerCase();
                return this.aiGeneratedTextMarkers.some(marker => normalizedValue.includes(marker));
            });
    }

    private getActionTextValues(manifest: C2paManifest): string[] {
        return manifest.assertions
            ?.flatMap(assertion => this.getActions(assertion.data))
            .flatMap(action => [
                this.getStringValue(action, 'description'),
                this.getStringValue(action, 'action'),
                this.getSoftwareAgentName(this.getObjectProperty(action, 'softwareAgent'))
            ])
            .filter((value): value is string => !!value && value.length > 0) ?? [];
    }

    private getClaimGeneratorName(manifest?: C2paManifest): string | undefined {
        const claimGeneratorInfo = manifest?.claim_generator_info?.find(info => info.name && info.name.length > 0);
        if (claimGeneratorInfo?.name && claimGeneratorInfo.version) {
            return this.normalizeDisplayValue(`${claimGeneratorInfo.name} ${claimGeneratorInfo.version}`);
        }

        return this.normalizeDisplayValue(claimGeneratorInfo?.name ?? manifest?.claim_generator);
    }

    private getActions(data: unknown): unknown[] {
        const actions = this.getObjectProperty(data, 'actions');
        if (!Array.isArray(actions)) {
            return [];
        }

        return actions;
    }

    private getSoftwareAgentName(value: unknown): string | undefined {
        if (typeof value === 'string') {
            return this.normalizeDisplayValue(value);
        }

        const name = this.getStringValue(value, 'name');
        const version = this.getStringValue(value, 'version');
        if (name && version) {
            return this.normalizeDisplayValue(`${name} ${version}`);
        }

        return this.normalizeDisplayValue(name);
    }

    private normalizeDisplayValue(value?: string): string | undefined {
        const normalizedValue = value?.replaceAll('_', ' ').trim();
        return normalizedValue && normalizedValue.length > 0 ? normalizedValue : undefined;
    }

    private getVerifyUrl(imageUrl: string): string {
        return `https://c2paviewer.com/?url=${encodeURIComponent(imageUrl)}`;
    }

    private getStringValue(value: unknown, propertyName: string): string | undefined {
        const property = this.getObjectProperty(value, propertyName);
        if (typeof property === 'string' && property.trim().length > 0) {
            return property.trim();
        }

        if (Array.isArray(property)) {
            return property
                .map(item => this.getStringValue(item, 'name') ?? this.getStringValue(item, '@name') ?? this.getStringValue(item, 'identifier'))
                .find(item => item && item.length > 0);
        }

        if (property === undefined || property === null) {
            return undefined;
        }

        return this.getStringValue(property, 'name') ?? this.getStringValue(property, '@name') ?? this.getStringValue(property, 'identifier');
    }

    private getObjectProperty(value: unknown, propertyName: string): unknown {
        if (!this.hasObjectProperty(value, propertyName)) {
            return undefined;
        }

        return value[propertyName];
    }

    private hasObjectProperty(value: unknown, propertyName: string): value is Record<string, unknown> {
        return typeof value === 'object' && value !== null && propertyName in value;
    }

    private getValidationFailures(results?: C2paValidationResults | null): C2paValidationStatus[] {
        return [
            ...(results?.activeManifest?.failure ?? []),
            ...(results?.ingredientDeltas?.flatMap(ingredient => ingredient.validationDeltas.failure ?? []) ?? [])
        ];
    }
}
